-- Q9 What is the count of each customer segment (New, Returning, Loyal)?

SELECT 
    CASE 
        WHEN frequency_of_purchases IN ('Weekly', 'Bi-Weekly', 'Fortnightly') THEN 'Loyal'
        WHEN frequency_of_purchases = 'Monthly' THEN 'Returning'
        WHEN frequency_of_purchases IN ('Quarterly', 'Annually', 'Every 3 Months') THEN 'New'
    END AS customer_segment,
    
    COUNT(*) AS total_customers

FROM customer_behaviour
GROUP BY customer_segment
ORDER BY total_customers DESC;


-- Business Problem: A lack of customer segmentation leads to generic, inefficient marketing strategies
-- .
-- Impact: Segmentation enables personalized marketing, allowing the company 
-- to apply different retention strategies for "Loyal" vs. "New" customers, ultimately increasing conversion rates
.



