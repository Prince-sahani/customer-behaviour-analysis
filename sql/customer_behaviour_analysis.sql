-- Q11 Are repeat buyers (more than five purchases) likely to subscribe?

SELECT 
    subscription_status,
    COUNT(*) AS total_customers,
    ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2 ) AS percentage
FROM customer_behaviour
WHERE previous_purchases > 5
GROUP BY subscription_status;


-- Business Problem: The relationship between customer loyalty (repeat purchases) and 
-- the adoption of the subscription plan is unclear
-- .
-- Impact: This helps improve subscription targeting by identifying why even loyal customers might not be subscribing, 
-- leading to better-tailored conversion campaigns
.





-- Q12 What is the revenue contribution of each age group?

SELECT 
    CASE 
        WHEN age BETWEEN 18 AND 25 THEN '18-25'
        WHEN age BETWEEN 26 AND 35 THEN '26-35'
        WHEN age BETWEEN 36 AND 50 THEN '36-50'
        ELSE '50+'
    END AS age_group,

    ROUND(SUM(purchase_amount_usd)::numeric, 2) AS total_revenue,

    ROUND(
        (
            SUM(purchase_amount_usd) * 100.0 
            / SUM(SUM(purchase_amount_usd)) OVER ()
        )::numeric,
        2
    ) AS revenue_percentage

FROM customer_behaviour
GROUP BY age_group
ORDER BY total_revenue DESC;


-- Business Problem: There is no visibility into which demographic age group generates the most revenue
-- .
-- Impact: This provides the visibility needed to execute age-based targeting 
-- enhances the overall efficiency of marketing campaigns by focusing on the most profitable age brackets
.


